/*
 * Chart Desk: Python indicators in My scripts.
 *
 * chartd lists the files of ~/chartdesk/indicators (GET /chartdesk/v1/py). For each one the app keeps a generated
 * OakScript indicator, "Py: <title>", that plots the series chartd computes in Python over the chart's own symbol
 * (request.security of PY:PY.<ID>.<ticker>, the ticker from syminfo.tickerid): it adds to any chart from the Indicators dialog (Personal > My
 * scripts), takes alerts and runs in the script screener like any script. Edit the Python file, not the script: the
 * script is written again when its file's title or placement changes. Checked at start and every minute.
 */
import * as kv from "../data/kv";
import { createScript, loadScript, saveCompiledMeta, saveSource } from "../data/oakscript-store";
import { translateWith } from "../i18n/translator";

const LIST = "http://127.0.0.1:8798/chartdesk/v1/py";
const MAP_KEY = "ot:chartdesk:py-scripts";

type PyIndicator = { id: string; title: string; overlay: boolean; error: string | null };

export function pySource(ind: PyIndicator, folder: string): string {
  const title = JSON.stringify(`Py: ${ind.title}`);
  return [
    `// Generated by Chart Desk from ${folder}/${ind.id.toLowerCase()}.py: edit that file, not this script.`,
    ind.error ? `// The Python file fails to load: ${ind.error.replace(/\n/g, " ")}` : null,
    `indicator(${title}, { overlay: ${ind.overlay} });`,
    // syminfo.tickerid is "EXCHANGE:TICKER": the ticker is what follows the colon.
    `plot(request.security("PY:PY.${ind.id}." + String(syminfo.tickerid).split(":").pop(), "", () => close), ${JSON.stringify(ind.title)});`,
    "",
  ].filter((l) => l != null).join("\n");
}

async function sync(): Promise<void> {
  const r = await fetch(LIST);
  if (!r.ok) return;
  const { folder, indicators } = (await r.json()) as { folder: string; indicators: PyIndicator[] };
  const map: Record<string, string> = JSON.parse(kv.getItem(MAP_KEY) ?? "{}");
  let changed = false;
  for (const ind of indicators) {
    const source = pySource(ind, folder);
    const known = map[ind.id] ? loadScript(map[ind.id]) : null;
    // Its title and placement before the first compile (the chart reads them when the script is added; the
    // compile then writes the whole surface).
    const name = translateWith("Py: {0}", ind.title);
    const meta = { title: name, overlay: ind.overlay };
    if (!known) {
      const s = createScript(name, source);
      saveCompiledMeta(s.id, meta);
      map[ind.id] = s.id;
      changed = true;
    } else if (known.source !== source) {
      saveSource(known.id, source);
      saveCompiledMeta(known.id, { ...(known.meta ?? {}), ...meta });
    }
  }
  if (changed) kv.setItem(MAP_KEY, JSON.stringify(map));
}

let started = false;
export function startPySync(): void {
  if (started) return;
  started = true;
  const run = () => void sync().catch(() => { /* chartd down: tried again in a minute */ });
  run();
  window.setInterval(run, 60_000);
}
